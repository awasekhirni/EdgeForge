//! # Real FFI Module
//!
//! ## Purpose
//! Provides safe wrapper functions around the unsafe llama.cpp C API.
//! This module is only compiled when `cfg(not(llama_stub))` — i.e., when
//! the `llama-backend` feature is enabled AND llama.cpp is built.
//!
//! ## What This File Does
//! - Includes the bindgen-generated bindings from `OUT_DIR/bindings.rs`
//! - Defines `LlamaModelInner` and `LlamaContextInner` (opaque wrappers)
//! - Provides safe wrapper functions: `load_model`, `tokenize`, `decode`,
//!   `sample_token`, `token_to_piece`, etc.
//! - All wrappers check for null pointers and convert errors to `FfiError`
//!
//! ## Safety
//! Every function in this module wraps an `unsafe` FFI call with:
//! 1. Null pointer checks
//! 2. Error code checking
//! 3. RAII cleanup on failure
//!
//! ## Dependencies
//! - bindgen-generated bindings (from `OUT_DIR/bindings.rs`)
//! - llama.cpp static library (linked by build.rs)

// Include the bindgen-generated bindings.
// This file is generated by build.rs when llama.cpp is successfully built.
include!(concat!(env!("OUT_DIR"), "/bindings.rs"));

use crate::{FfiError, LlamaContext, LlamaGenerationParams, LlamaModel, LlamaModelParams};
use std::ffi::CString;
use std::path::Path;

/// Inner model handle — wraps the raw `*mut llama_model` pointer.
/// Automatically freed on drop via `llama_model_free`.
pub struct LlamaModelInner {
    ptr: *mut llama_model,
}

impl Drop for LlamaModelInner {
    fn drop(&mut self) {
        if !self.ptr.is_null() {
            unsafe { llama_model_free(self.ptr) }
        }
    }
}

/// Inner context handle — wraps the raw `*mut llama_context` pointer.
/// Automatically freed on drop via `llama_free`.
pub struct LlamaContextInner {
    ptr: *mut llama_context,
}

impl Drop for LlamaContextInner {
    fn drop(&mut self) {
        if !self.ptr.is_null() {
            unsafe { llama_free(self.ptr) }
        }
    }
}

/// Initialize the llama.cpp backend (call once at startup).
///
/// ## Purpose
/// Calls `llama_backend_init()` to initialize the backend. Must be called
/// before any other llama.cpp function.
///
/// ## Safety
/// Must be called exactly once. Uses `std::sync::Once` for thread safety.
static BACKEND_INIT: std::sync::Once = std::sync::Once::new();

fn ensure_backend_init() {
    BACKEND_INIT.call_once(|| unsafe { llama_backend_init(false) });
}

/// Load a model from a GGUF file.
///
/// ## Parameters
/// - `path`: Path to the `.gguf` model file on SSD
/// - `params`: Model loading parameters (context size, GPU layers, mmap, mlock)
///
/// ## Returns
/// `Ok(LlamaModel)` on success, `Err(FfiError)` on failure.
///
/// ## Errors
/// - `FfiError::InvalidArgument` if the path is not valid UTF-8
/// - `FfiError::NullPointer` if llama.cpp returns a null model pointer
/// - `FfiError::Ffi` if the model file cannot be loaded
///
/// ## Dependencies
/// - `llama_model_load_from_file()` — loads the GGUF file
/// - `ensure_backend_init()` — initializes the backend if needed
///
/// ## Safety
/// The returned `LlamaModel` owns the raw pointer and frees it on drop.
pub fn load_model(path: &Path, params: &LlamaModelParams) -> Result<LlamaModel, FfiError> {
    ensure_backend_init();

    let path_str = path
        .to_str()
        .ok_or_else(|| FfiError::InvalidArgument("path is not valid UTF-8".into()))?;
    let path_c = CString::new(path_str)
        .map_err(|e| FfiError::InvalidArgument(format!("path contains null byte: {e}")))?;

    // Build model params.
    let mut c_params = unsafe { std::mem::zeroed::<llama_model_params>() };
    c_params.n_gpu_layers = params.n_gpu_layers as i32;
    c_params.use_mmap = params.use_mmap;
    c_params.use_mlock = params.use_mlock;

    let model_ptr = unsafe { llama_model_load_from_file(path_c.as_ptr(), c_params) };
    if model_ptr.is_null() {
        return Err(FfiError::NullPointer);
    }

    Ok(LlamaModel {
        inner: LlamaModelInner { ptr: model_ptr },
    })
}

/// Tokenize text into llama.cpp token IDs.
///
/// ## Parameters
/// - `model`: Opaque model handle
/// - `text`: Text to tokenize
/// - `add_bos`: Whether to prepend a beginning-of-sequence token
///
/// ## Returns
/// `Ok(Vec<i32>)` — the token IDs.
///
/// ## Errors
/// - `FfiError::Ffi` if tokenization fails
///
/// ## Dependencies
/// - `llama_tokenize()` — the C API tokenization function
pub fn tokenize(model: &LlamaModel, text: &str, add_bos: bool) -> Result<Vec<i32>, FfiError> {
    let text_c = CString::new(text)
        .map_err(|e| FfiError::InvalidArgument(format!("text contains null byte: {e}")))?;

    // First call: determine the required buffer size.
    let n_tokens = unsafe {
        llama_tokenize(
            model.inner.ptr,
            text_c.as_ptr(),
            text.len() as i32,
            std::ptr::null_mut(),
            0,
            add_bos,
            true,
        )
    };

    if n_tokens < 0 {
        return Err(FfiError::Ffi(format!(
            "tokenization failed (n_tokens={n_tokens})"
        )));
    }

    // Second call: actually tokenize.
    let mut tokens = vec![0i32; n_tokens as usize];
    let written = unsafe {
        llama_tokenize(
            model.inner.ptr,
            text_c.as_ptr(),
            text.len() as i32,
            tokens.as_mut_ptr(),
            n_tokens,
            add_bos,
            true,
        )
    };

    if written < 0 {
        return Err(FfiError::Ffi(format!(
            "tokenization failed on second call (written={written})"
        )));
    }

    tokens.truncate(written as usize);
    Ok(tokens)
}

/// Detokenize a single token ID into text.
///
/// ## Parameters
/// - `model`: Opaque model handle
/// - `token`: Token ID to decode
///
/// ## Returns
/// `Ok(String)` — the decoded text piece.
///
/// ## Dependencies
/// - `llama_token_to_piece()` — the C API detokenization function
pub fn token_to_piece(model: &LlamaModel, token: i32) -> Result<String, FfiError> {
    let mut buf = vec![0u8; 64]; // 64 bytes should be enough for most tokens
    let n_written = unsafe {
        llama_token_to_piece(
            model.inner.ptr,
            token,
            buf.as_mut_ptr() as *mut std::os::raw::c_char,
            buf.len() as i32,
        )
    };

    if n_written < 0 {
        return Err(FfiError::Ffi(format!(
            "token_to_piece failed (token={token})"
        )));
    }

    buf.truncate(n_written as usize);
    String::from_utf8(buf).map_err(|e| FfiError::Ffi(format!("invalid UTF-8 in token: {e}")))
}

/// Create a llama.cpp context for a model.
///
/// ## Parameters
/// - `model`: Opaque model handle
/// - `n_ctx`: Context window size (number of tokens)
///
/// ## Returns
/// `Ok(LlamaContext)` — a new context with KV cache.
///
/// ## Dependencies
/// - `llama_new_context_with_model()` — creates the context
pub fn new_context(model: &LlamaModel, n_ctx: u32) -> Result<LlamaContext, FfiError> {
    let mut c_params = unsafe { std::mem::zeroed::<llama_context_params>() };
    c_params.n_ctx = n_ctx as u32;
    c_params.n_batch = 512;
    c_params.n_threads = std::thread::available_parallelism()
        .map(|n| n.get() as i32)
        .unwrap_or(4);
    c_params.n_threads_batch = c_params.n_threads;

    let ctx_ptr = unsafe { llama_new_context_with_model(model.inner.ptr, c_params) };
    if ctx_ptr.is_null() {
        return Err(FfiError::NullPointer);
    }

    Ok(LlamaContext {
        inner: LlamaContextInner { ptr: ctx_ptr },
    })
}

/// Decode a batch of tokens (run one forward pass).
///
/// ## Parameters
/// - `ctx`: Opaque context handle (mutated)
/// - `tokens`: Token IDs to process
///
/// ## Returns
/// `Ok(())` on success.
///
/// ## Errors
/// - `FfiError::Ffi` if the decode call fails
///
/// ## Dependencies
/// - `llama_decode()` — runs the forward pass
pub fn decode(ctx: &mut LlamaContext, tokens: &[i32]) -> Result<(), FfiError> {
    // Build a llama_batch.
    let mut batch = unsafe { std::mem::zeroed::<llama_batch>() };
    batch.n_tokens = tokens.len() as i32;
    batch.token = tokens.as_ptr() as *mut llama_token;
    batch.pos = (0..tokens.len() as i32).collect::<Vec<_>>().as_ptr() as *mut llama_pos;
    batch.n_seq_id = (0..tokens.len()).map(|_| 1).collect::<Vec<_>>().as_ptr() as *mut i32;
    batch.seq_id = (0..tokens.len())
        .map(|_| [1i32].as_ptr())
        .collect::<Vec<_>>()
        .as_ptr() as *mut *const llama_seq_id;
    batch.logits = std::ptr::null_mut();

    let result = unsafe { llama_decode(ctx.inner.ptr, batch) };
    if result != 0 {
        return Err(FfiError::Ffi(format!(
            "llama_decode failed (error code={result})"
        )));
    }
    Ok(())
}

/// Sample the next token from the model's logits.
///
/// ## Parameters
/// - `ctx`: Opaque context handle (mutated — reads logits from last decode)
/// - `temp`: Sampling temperature (0.0 = greedy, 1.0 = creative)
/// - `top_p`: Top-p sampling threshold (0.0–1.0)
///
/// ## Returns
/// `Ok(i32)` — the sampled token ID.
///
/// ## Dependencies
/// - `llama_get_logits_ith()` — gets logits for the last token
/// - `llama_token_eos()` — gets the end-of-sequence token
pub fn sample_token(ctx: &mut LlamaContext, temp: f32, top_p: f32) -> Result<i32, FfiError> {
    // Get logits for the last token.
    let n_tokens = unsafe { llama_get_batch_size(ctx.inner.ptr) } as i32;
    if n_tokens <= 0 {
        return Err(FfiError::Ffi("no tokens in context".into()));
    }

    let logits = unsafe { llama_get_logits_ith(ctx.inner.ptr, n_tokens - 1) };
    if logits.is_null() {
        return Err(FfiError::NullPointer);
    }

    // Simple greedy sampling for now (temp == 0) or temperature sampling.
    // In production, use llama_sample_token() with a sampler chain.
    let n_vocab = unsafe { llama_n_vocab(unsafe { llama_get_model(ctx.inner.ptr) }) } as usize;

    if temp <= 0.0 {
        // Greedy: return argmax.
        let mut best_token = 0i32;
        let mut best_logit = f32::NEG_INFINITY;
        for i in 0..n_vocab {
            let logit = unsafe { *logits.add(i) };
            if logit > best_logit {
                best_logit = logit;
                best_token = i as i32;
            }
        }
        Ok(best_token)
    } else {
        // Temperature sampling with top-p.
        let mut logit_vec: Vec<(i32, f32)> = (0..n_vocab)
            .map(|i| (i as i32, unsafe { *logits.add(i) } / temp))
            .collect();
        logit_vec.sort_by(|a, b| b.1.partial_cmp(&a.1).unwrap_or(std::cmp::Ordering::Equal));

        // Apply top-p.
        let exp_sum: f32 = logit_vec.iter().map(|(_, l)| l.exp()).sum();
        let mut cum_prob = 0.0;
        let top_p_count = logit_vec
            .iter()
            .take_while(|(_, l)| {
                cum_prob += l.exp() / exp_sum;
                cum_prob < top_p
            })
            .count()
            .max(1);

        // Sample from the top-p candidates.
        // For simplicity, pick the top candidate (greedy within top-p).
        // In production, use a proper random sampler.
        Ok(logit_vec[0].0)
    }
}

/// Get the model's vocabulary size.
pub fn n_vocab(model: &LlamaModel) -> Result<u32, FfiError> {
    Ok(unsafe { llama_n_vocab(model.inner.ptr) } as u32)
}

/// Get the model's embedding dimension.
pub fn n_embd(model: &LlamaModel) -> Result<u32, FfiError> {
    Ok(unsafe { llama_n_embd(model.inner.ptr) } as u32)
}

/// Get the model's layer count.
pub fn n_layers(model: &LlamaModel) -> Result<u32, FfiError> {
    Ok(unsafe { llama_n_layer(model.inner.ptr) } as u32)
}

